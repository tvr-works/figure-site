import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { compileGuideLibrary } from '../src/content/catalog';

const read = async (path: string): Promise<unknown> => JSON.parse(await readFile(new URL(path, import.meta.url), 'utf8'));
const native = await read('../content/native-help.json');
const map = await read('../docs/design/guide-subject-map.json');
const slugs = await read('../content/published-guides.json');
const context = await read('../content/guide-context.json');
if (!Array.isArray(slugs) || !slugs.every(slug => typeof slug === 'string')) throw new Error('Published guides must be a list of slugs.');
const library = compileGuideLibrary(native, map, slugs, context);
const directory = new URL('../src/content/generated/', import.meta.url);
// Generated output is a publication boundary. Remove stale chunks when a subject
// is unpublished, then emit an independent module for each approved article.
await rm(directory, { recursive: true, force: true });
await mkdir(new URL('articles/', directory), { recursive: true });
await writeFile(new URL('summaries.ts', directory), `// Generated by npm run content.\nimport type { GuideSummary } from '../catalog';\nexport const guideSummaries: GuideSummary[] = ${JSON.stringify(library.summaries, null, 2)};\n`);
for (const article of library.articles) await writeFile(new URL(`articles/${article.slug}.json`, directory), JSON.stringify(article, null, 2) + '\n');
console.log(`Validated ${library.recipeCount} native recipes across ${library.guideCount} subjects; prepared ${library.articles.length} published guides.`);
