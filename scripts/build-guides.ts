import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { compileGuideLibrary } from '../src/content/catalog';

const read = async (path: string): Promise<unknown> => JSON.parse(await readFile(new URL(path, import.meta.url), 'utf8'));
const native = await read('../content/native-help.json');
const map = await read('../docs/design/guide-subject-map.json');
const slugs = await read('../content/published-guides.json');
if (!Array.isArray(slugs) || !slugs.every(slug => typeof slug === 'string')) throw new Error('Published guides must be a list of slugs.');
const library = compileGuideLibrary(native, map, slugs);
const directory = new URL('../src/content/generated/', import.meta.url);
await mkdir(directory, { recursive: true });
await writeFile(new URL('library.ts', directory), `// Generated by npm run content.\nimport type { GuideArticle, GuideSummary } from '../catalog';\nexport const guideSummaries: GuideSummary[] = ${JSON.stringify(library.summaries, null, 2)};\nexport const guideArticles: GuideArticle[] = ${JSON.stringify(library.articles, null, 2)};\n`);
console.log(`Validated ${library.recipeCount} native recipes across ${library.guideCount} subjects; prepared ${library.articles.length} published guide.`);
